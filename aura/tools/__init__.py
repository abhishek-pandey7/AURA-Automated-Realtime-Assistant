import pkgutil
import importlib
import importlib.util
from pathlib import Path
from typing import Callable

ALL_TOOL_DEFS = []
_dispatch_map = {}
_custom_tools = {}   # name -> (schema, func), registered from code via register_tool
_loaded = False


def _register_module(module, module_name: str):
    # Find TOOL_DEF or TOOL_DEFS
    defs = []
    if hasattr(module, "TOOL_DEFS"):
        defs = getattr(module, "TOOL_DEFS")
    elif hasattr(module, "TOOL_DEF"):
        defs = [getattr(module, "TOOL_DEF")]

    for tdef in defs:
        if isinstance(tdef, dict) and "function" in tdef and "name" in tdef["function"]:
            ALL_TOOL_DEFS.append(tdef)
            tool_name = tdef["function"]["name"]

            # Map to function reference
            if hasattr(module, tool_name) and callable(getattr(module, tool_name)):
                _dispatch_map[tool_name] = getattr(module, tool_name)
            elif module_name == "shell" and tool_name == "bash":
                _dispatch_map[tool_name] = getattr(module, "run")


def _init_tools():
    global _loaded
    from aura.config import user_tools_dir

    ALL_TOOL_DEFS.clear()
    _dispatch_map.clear()

    pkg_dir = Path(__file__).resolve().parent
    for _, module_name, ispkg in pkgutil.iter_modules([str(pkg_dir)]):
        if ispkg: continue
        try:
            module = importlib.import_module(f"aura.tools.{module_name}")
            _register_module(module, module_name)
        except Exception:
            pass # Ignore tools whose optional dependencies aren't installed

    # Tools generated by watch-and-learn live outside the package so pip installs can write them
    for path in sorted(user_tools_dir().glob("*.py")):
        try:
            spec = importlib.util.spec_from_file_location(f"aura_user_tools.{path.stem}", path)
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            _register_module(module, path.stem)
        except Exception:
            pass # Ignore broken generated tools on startup

    for schema, func in _custom_tools.values():
        ALL_TOOL_DEFS.append(schema)
        _dispatch_map[schema["function"]["name"]] = func

    _loaded = True


def get_tool_defs() -> list[dict]:
    if not _loaded:
        _init_tools()
    return ALL_TOOL_DEFS


def register_tool(func: Callable[..., str], schema: dict | None = None,
                  description: str | None = None):
    """Make a Python function available to the agent as a tool.

    Pass a full OpenAI tool schema, or just a description to get a schema built from the
    function's parameters (each typed as a string unless annotated int/float/bool).
    """
    if schema is None:
        schema = _schema_from_function(func, description)
    name = schema["function"]["name"]
    _custom_tools[name] = (schema, func)
    if _loaded:
        ALL_TOOL_DEFS[:] = [d for d in ALL_TOOL_DEFS if d["function"]["name"] != name]
        ALL_TOOL_DEFS.append(schema)
        _dispatch_map[name] = func
    return func


def _schema_from_function(func: Callable, description: str | None) -> dict:
    import inspect
    json_types = {int: "integer", float: "number", bool: "boolean", str: "string"}
    properties, required = {}, []
    for pname, param in inspect.signature(func).parameters.items():
        properties[pname] = {"type": json_types.get(param.annotation, "string")}
        if param.default is inspect.Parameter.empty:
            required.append(pname)
    return {
        "type": "function",
        "function": {
            "name": func.__name__,
            "description": description or (inspect.getdoc(func) or func.__name__),
            "parameters": {"type": "object", "properties": properties, "required": required},
        },
    }


def dispatch(name: str, inputs: dict) -> str:
    if not _loaded:
        _init_tools()
    func = _dispatch_map.get(name)
    if func:
        try:
            res = func(**inputs)
            return res if res is not None else f"[ AURA ] Executed: {name}"
        except TypeError as e:
            # Fallback for unexpected missing properties where **inputs fails mapping exactly
            return f"[ AURA ] Tool arguments error '{name}': {e}"
        except Exception as e:
            return f"[ AURA ] Tool execution error '{name}': {e}"

    return f"[ AURA ] Unknown tool: {name}"
